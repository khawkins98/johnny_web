#!/usr/bin/env node
/**
 * scene-flow-doc.mjs — generates docs/scene-flows/<ADSNAME>.md from the real
 * ADS bytecode, using the pure extractor at src/dgds/scripting/scene-flow.mjs.
 *
 * Each gag scene's authored logic (IF_NOT_PLAYED/IF_PLAYED/IF_RUNNING guards,
 * ADD_SCENE/STOP_SCENE actions, RANDOM_START..RANDOM_END picks) is rendered as
 * a readable outline plus a mermaid flowchart of the scene's dependency graph,
 * generated FROM the data so the docs can never drift from the game logic.
 *
 * Sub-scene names (the ADD_SCENE targets, e.g. "2:21") come from the resource
 * TTMs: for a resource {id, name} referenced by an ADS file, that TTM's own
 * `tags` list maps its sequence tag -> a human name, and the ADD_SCENE's slot
 * param equals the resource id. See extractSceneFlow's caller-injected
 * `label` below.
 *
 * SCRANTIC data is proprietary + gitignored (absent in CI); this is gated on
 * `hasData` and exits 0 with a message when it's missing, same as the other
 * data-driven tooling here.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hasData, loadAds } from '../../src/dgds/scripting/__tests__/support/drive-gag.mjs';
import { extractSceneFlow } from '../../src/dgds/scripting/scene-flow.mjs';

const HEADER =
    'Generated by `tools/faithfulness-oracle/scene-flow-doc.mjs` from the original ADS ' +
    'data — do not edit by hand; regenerate with `node tools/faithfulness-oracle/scene-flow-doc.mjs`.';

const ADS_FILES = [
    'ACTIVITY.ADS',
    'BUILDING.ADS',
    'FISHING.ADS',
    'JOHNNY.ADS',
    'MARY.ADS',
    'MISCGAG.ADS',
    'STAND.ADS',
    'SUZY.ADS',
    'VISITOR.ADS',
    'WALKSTUF.ADS',
];

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../docs/scene-flows');

/** Build a `label(slot, tag) -> name` resolver from an ADS file's resource TTMs. */
const buildLabelResolver = (ads, cache) => {
    const names = new Map();
    for (const res of ads.resources || []) {
        if (!cache.has(res.name)) {
            let tags = [];
            try {
                tags = loadAds(res.name).tags || [];
            } catch {
                tags = [];
            }
            cache.set(res.name, tags);
        }
        for (const t of cache.get(res.name)) {
            names.set(`${res.id}:${t.id}`, (t.description || '').trim());
        }
    }
    return (slot, tag) => names.get(`${slot}:${tag}`) || `${slot}:${tag}`;
};

const guardText = (guard) => {
    const phrase = (kind, name) =>
        ({
            start: 'at the start',
            after: `after "${name}"`,
            while: `while "${name}" is on screen`,
            ifNotRunning: `if "${name}" isn't on screen`,
            always: 'always',
        })[kind] ?? kind;

    if (guard.kind === 'always') return 'always';
    if (!guard.refs) return phrase(guard.kind, guard.name);
    const joiner = guard.combinator === 'and' ? '" and "' : '" or "';
    const names = guard.refs.map((r) => r.name);
    return phrase(guard.kind, names[0]).replace(`"${names[0]}"`, `"${names.join(joiner)}"`);
};

const renderOutline = (flow) => {
    const lines = [];
    for (const step of flow.steps) {
        const targets = [
            ...step.adds.map((a) => `"${a.name}"`),
            ...step.stops.map((s) => `stop "${s.name}"`),
        ];
        if (!targets.length) continue;
        const lead = step.random ? 'picks one of' : '→';
        lines.push(`- **${guardText(step.guard)}** ${lead} ${targets.join(', ')}`);
    }
    return lines.length ? lines.join('\n') : '_(no scripted steps)_';
};

const renderMermaid = (flow) => {
    if (!flow.edges.length) return '';
    const ids = new Map();
    let n = 0;
    const nid = (key) => {
        if (!ids.has(key)) ids.set(key, `s${n++}`);
        return ids.get(key);
    };
    const nameByKey = new Map(flow.nodes.map((node) => [node.key, node.name]));
    let mm = 'flowchart TD\n';
    for (const node of flow.nodes) {
        mm += `  ${nid(node.key)}["${(nameByKey.get(node.key) || node.key).replace(/"/g, "'")}"]\n`;
    }
    for (const [from, to] of flow.edges) {
        mm += `  ${nid(from)} --> ${nid(to)}\n`;
    }
    return '```mermaid\n' + mm + '```';
};

const renderGagSection = (ads, adsName, scene, label) => {
    const flow = extractSceneFlow(scene, { label });
    let md = `## ${scene.tagId.description} (\`${adsName}\` tag ${scene.tagId.id})\n\n`;
    md += renderOutline(flow) + '\n';
    const mermaid = renderMermaid(flow);
    if (mermaid) md += '\n' + mermaid + '\n';
    return md;
};

const renderAdsDoc = (adsName, ads, label) => {
    let md = `# ${adsName} scene flows\n\n${HEADER}\n\n`;
    md +=
        'Pairs with [../story-over-time.md](../story-over-time.md), which covers the calendar-driven ' +
        'story arc across gags; this doc covers the scripted flow *within* each of this file\'s gags.\n\n';
    for (const scene of ads.scenes) {
        md += renderGagSection(ads, adsName, scene, label) + '\n';
    }
    return md;
};

const renderIndex = (entries) => {
    let md = `# Scene flows\n\n${HEADER}\n\n`;
    md +=
        'Human-readable flows of each gag\'s authored ADS scripting — guards, branches, and ' +
        'RANDOM picks — rendered from the real bytecode so they can\'t drift from it. Pairs with ' +
        '[../story-over-time.md](../story-over-time.md) (the calendar-driven story arc across gags).\n\n';
    for (const { adsName, gagCount } of entries) {
        md += `- [${adsName}](./${adsName}.md) — ${gagCount} gag${gagCount === 1 ? '' : 's'}\n`;
    }
    return md;
};

const main = () => {
    if (!hasData) {
        console.log('scene-flow-doc: no game data present (public/data/*), skipping generation.');
        process.exit(0);
    }

    mkdirSync(outDir, { recursive: true });
    const ttmTagCache = new Map();
    const entries = [];

    for (const adsName of ADS_FILES) {
        const ads = loadAds(adsName);
        const label = buildLabelResolver(ads, ttmTagCache);
        const md = renderAdsDoc(adsName, ads, label);
        writeFileSync(path.join(outDir, `${adsName}.md`), md);
        entries.push({ adsName, gagCount: ads.scenes.length });
        console.log(`wrote docs/scene-flows/${adsName}.md (${ads.scenes.length} gags)`);
    }

    writeFileSync(path.join(outDir, 'README.md'), renderIndex(entries));
    console.log('wrote docs/scene-flows/README.md');
};

main();
